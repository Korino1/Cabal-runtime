#[test]
fn collector_and_projection_limits_are_hard_and_reported() {
    let (temp, state) = fixture();
    let mut crowded = String::new();
    for index in 0..(MAX_RUST_SYMBOLS_PER_FILE + 2) {
        crowded.push_str(&format!("fn symbol_{index}() {{ Thing; }}\n"));
    }
    for _ in 0..(MAX_IMPORTS_PER_FILE + 2) {
        crowded.push_str("use std::fmt;\n");
    }
    fs::write(temp.path().join("src/crowded.rs"), crowded).unwrap();
    let value = index(&temp, &state);
    let crowded = value
        .files
        .iter()
        .find(|file| file.path == "src/crowded.rs")
        .unwrap();
    let RustParseStatus::Parsed { facts } = &crowded.rust else {
        panic!("crowded file must parse");
    };
    assert_eq!(facts.definitions.len(), MAX_RUST_SYMBOLS_PER_FILE);
    assert_eq!(facts.imports.len(), MAX_IMPORTS_PER_FILE);
    assert!(facts.omissions.symbols >= 2);
    assert!(facts.omissions.imports >= 2);
    assert_eq!(facts.references.len(), MAX_RUST_REFERENCES_PER_FILE);
    assert!(facts.omissions.references >= 2);

    let mut projected = RepositoryInventory {
        schema: INVENTORY_SCHEMA.to_owned(),
        indexed_files: 300,
        projected_files: 0,
        omitted_files: 0,
        source_paths: (0..300)
            .map(|index| format!("src/{index}-{}", "x".repeat(512)))
            .collect(),
        test_paths: Vec::new(),
        manifest_paths: Vec::new(),
        configuration_paths: Vec::new(),
        packages: Vec::new(),
        indexed_packages: 0,
        omitted_packages: 0,
        indexed_targets: 0,
        omitted_targets: 0,
        projection_complete: true,
        completeness: Completeness::Complete,
    };
    bound_inventory(&mut projected);
    update_inventory_counts(&mut projected, 0);
    assert!(total_inventory_paths(&projected) <= MAX_INVENTORY_PATHS);
    assert!(inventory_bytes(&projected).len() <= MAX_INVENTORY_BYTES);
    assert_eq!(projected.omitted_files, 300 - projected.projected_files);
    assert!(!projected.projection_complete);
}

#[test]
fn rejects_missing_git_or_external_state_root() {
    let temp = tempfile::tempdir().unwrap();
    fs::create_dir_all(temp.path().join("src")).unwrap();
    assert!(matches!(
        refresh(temp.path(), &temp.path().join("state")),
        Err(RepositoryMapError::NoGitServiceDirectory)
    ));
    fs::create_dir(temp.path().join(".git")).unwrap();
    assert!(matches!(
        refresh(temp.path(), tempfile::tempdir().unwrap().path()),
        Err(RepositoryMapError::StateRootOutsideGitService)
    ));
}

#[test]
fn concurrent_refreshes_are_serialized_and_leave_valid_state() {
    let (temp, state) = fixture();
    let workspace = temp.path().to_path_buf();
    let handles = (0..6)
        .map(|_| {
            let workspace = workspace.clone();
            let state = state.clone();
            std::thread::spawn(move || refresh(&workspace, &state).unwrap())
        })
        .collect::<Vec<_>>();
    for handle in handles {
        assert!(!handle.join().unwrap().index.files.is_empty());
    }
    assert!(load(&state).unwrap().is_some());
}

#[cfg(unix)]
#[test]
fn symlinks_are_omitted_without_traversal() {
    use std::os::unix::fs::symlink;
    let (temp, state) = fixture();
    symlink(temp.path().join("src"), temp.path().join("linked-src")).unwrap();
    let value = index(&temp, &state);
    assert_eq!(value.omissions.symlinks, 1);
    assert!(
        !value
            .files
            .iter()
            .any(|file| file.path.starts_with("linked-src/"))
    );
}

#[cfg(unix)]
#[test]
fn state_root_symlink_escape_is_rejected() {
    use std::os::unix::fs::symlink;
    let (temp, _) = fixture();
    let external = tempfile::tempdir().unwrap();
    let runtime_root = temp.path().join(".git/cabal-runtime");
    fs::create_dir(&runtime_root).unwrap();
    let state = runtime_root.join("repository-map");
    symlink(external.path(), &state).unwrap();

    assert!(matches!(
        refresh(temp.path(), &state),
        Err(RepositoryMapError::StateRootOutsideGitService)
    ));
    assert!(external.path().read_dir().unwrap().next().is_none());
}
