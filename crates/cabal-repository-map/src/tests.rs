use super::*;
use std::fs;
use tempfile::TempDir;

fn fixture() -> (TempDir, PathBuf) {
    let temp = tempfile::tempdir().unwrap();
    let root = temp.path();
    fs::create_dir(root.join(".git")).unwrap();
    fs::create_dir_all(root.join("src")).unwrap();
    fs::create_dir_all(root.join("tests")).unwrap();
    fs::create_dir_all(root.join("dep/src")).unwrap();
    fs::write(root.join("Cargo.toml"), "[package]\nname = \"fixture\"\nversion = \"0.1.0\"\nedition = \"2024\"\n[dependencies]\ndep = { path = \"dep\" }\n").unwrap();
    fs::write(
        root.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"dep\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"fixture\"\nversion = \"0.1.0\"\ndependencies = [\n \"dep\",\n]\n",
    )
    .unwrap();
    fs::write(
        root.join("dep/Cargo.toml"),
        "[package]\nname = \"dep\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
    )
    .unwrap();
    fs::write(root.join("dep/src/lib.rs"), "pub struct Dependency;\n").unwrap();
    fs::write(root.join("src/lib.rs"), "pub mod api;\npub use crate::api::Thing as PublicThing;\nuse std::{fmt as formatting, collections::*};\n#[derive(Debug)] pub struct Thing;\npub trait Runner { fn run(&self); }\nimpl Thing { pub fn execute() {} }\nimpl Runner for Thing { fn run(&self) {} }\npub fn call() { api::Thing; }\n#[cfg(test)] mod inner { #[test] fn unit_case() { super::Thing::execute(); super::call(); } }\n").unwrap();
    fs::write(root.join("src/api.rs"), "pub struct Thing;\n").unwrap();
    fs::write(
        root.join("tests/integration.rs"),
        "#[test] fn integration_case() {}\n",
    )
    .unwrap();
    let state = temp.path().join(".git/cabal-runtime/repository-map");
    (temp, state)
}
fn index(temp: &TempDir, state: &Path) -> RepositoryMapIndex {
    refresh(temp.path(), state).unwrap().index
}

#[test]
fn deterministic_bytes_and_known_syntactic_corpus() {
    let (temp, state) = fixture();
    let first = index(&temp, &state);
    assert!(
        !first
            .files
            .iter()
            .any(|file| file.path.starts_with(".git/"))
    );
    let raw_first = fs::read(state.join(INDEX_FILE)).unwrap();
    let second = index(&temp, &state);
    let raw_second = fs::read(state.join(INDEX_FILE)).unwrap();
    assert_eq!(raw_first, raw_second);
    assert_eq!(first, second);
    assert_eq!(find_symbols(&first, "Thing").len(), 2);
    assert_eq!(find_imports(&first, "std::fmt").len(), 1);
    assert!(!find_references(&first, "api::Thing").is_empty());
    assert_eq!(find_tests(&first, "integration_case").len(), 1);
    assert_eq!(find_symbols(&first, "Thing::execute").len(), 1);
    assert_eq!(find_symbols(&first, "Runner::run").len(), 1);
    let associated = find_associated_tests(&first, "Thing::execute");
    assert_eq!(associated.len(), 1);
    assert_eq!(associated[0].test.name, "unit_case");
    let file = first
        .files
        .iter()
        .find(|file| file.path == "src/lib.rs")
        .unwrap();
    let RustParseStatus::Parsed { facts } = &file.rust else {
        panic!("Rust corpus must parse");
    };
    assert!(facts.modules.iter().any(|module| module.name == "api"));
    assert!(
        facts
            .definitions
            .iter()
            .any(|definition| definition.name == "call")
    );
    assert!(
        facts
            .reference_edges
            .iter()
            .any(|path| path == "api::Thing")
    );
}

#[test]
fn refresh_reuses_changes_and_deletes() {
    let (temp, state) = fixture();
    let first = index(&temp, &state);
    assert_eq!(first.files.len(), 7);
    let unchanged = refresh(temp.path(), &state).unwrap();
    assert_eq!(unchanged.reused_files, 7);
    assert_eq!(unchanged.reparsed_files, 0);
    fs::write(temp.path().join("src/api.rs"), "pub struct Changed;\n").unwrap();
    let changed = refresh(temp.path(), &state).unwrap();
    assert_eq!(changed.reparsed_files, 1);
    assert_eq!(changed.reused_files, 6);
    fs::remove_file(temp.path().join("tests/integration.rs")).unwrap();
    let deleted = refresh(temp.path(), &state).unwrap();
    assert_eq!(deleted.deleted_files, 1);
    assert!(
        !deleted
            .index
            .files
            .iter()
            .any(|file| file.path == "tests/integration.rs")
    );
}

#[test]
fn malformed_oversize_and_bounds_are_explicit() {
    let (temp, state) = fixture();
    fs::write(temp.path().join("src/broken.rs"), "fn {\n").unwrap();
    fs::write(
        temp.path().join("src/large.rs"),
        vec![b'x'; MAX_INDEXED_FILE_BYTES as usize + 1],
    )
    .unwrap();
    let result = index(&temp, &state);
    assert_eq!(result.omissions.malformed_rust, 1);
    assert_eq!(result.omissions.oversized_files, 1);
    assert_ne!(result.completeness, Completeness::Complete);
    assert!(matches!(
        result
            .files
            .iter()
            .find(|file| file.path == "src/broken.rs")
            .unwrap()
            .rust,
        RustParseStatus::Malformed
    ));
    assert!(matches!(
        result
            .files
            .iter()
            .find(|file| file.path == "src/large.rs")
            .unwrap()
            .rust,
        RustParseStatus::Oversized
    ));
    assert!(
        result
            .files
            .iter()
            .find(|file| file.path == "src/large.rs")
            .unwrap()
            .sha256
            .is_none()
    );
}

#[test]
fn corrupt_and_incompatible_index_rebuilds() {
    let (temp, state) = fixture();
    fs::create_dir_all(&state).unwrap();
    fs::write(state.join(INDEX_FILE), b"not json").unwrap();
    assert!(load(&state).unwrap().is_none());
    let rebuilt = refresh(temp.path(), &state).unwrap();
    assert_eq!(rebuilt.index.schema, INDEX_SCHEMA);
    let mut incompatible = rebuilt.index;
    incompatible.schema = "old".to_owned();
    fs::write(
        state.join(INDEX_FILE),
        serde_json::to_vec(&incompatible).unwrap(),
    )
    .unwrap();
    assert!(current(&state).unwrap().is_none());
}

#[test]
fn cargo_fixture_and_projection_do_not_leak() {
    let (temp, state) = fixture();
    fs::write(temp.path().join(".hidden.rs"), "pub struct Hidden;\n").unwrap();
    let value = index(&temp, &state);
    assert!(value.cargo.available);
    assert!(
        value
            .cargo
            .packages
            .iter()
            .any(|package| package.name == "fixture")
    );
    assert!(
        value
            .cargo
            .dependency_edges
            .iter()
            .any(|edge| edge.dependency == "dep")
    );
    assert!(
        value
            .cargo
            .packages
            .iter()
            .flat_map(|package| &package.targets)
            .any(|target| target.kinds.iter().any(|kind| kind == "lib"))
    );
    let inventory = inventory(&value);
    let raw = String::from_utf8(inventory_bytes(&inventory)).unwrap();
    assert!(raw.len() <= MAX_INVENTORY_BYTES);
    assert!(!raw.contains(&temp.path().to_string_lossy().to_string()));
    assert!(!raw.contains("pub struct Thing"));
    assert!(!raw.contains("repository-map"));
    assert_eq!(inventory.schema, INVENTORY_SCHEMA);
    let visible = visible_inventory(&value);
    assert!(!visible.source_paths.iter().any(|path| path == ".hidden.rs"));
    assert!(visible.omitted_files >= 1);
    assert!(!visible.projection_complete);
    assert!(
        estimated_visible_file_list_bytes(&value)
            < value.files.iter().map(|file| file.path.len() + 1).sum()
    );
}

#[test]
fn manifest_change_refreshes_cargo_facts_and_gitignore_is_obeyed() {
    let (temp, state) = fixture();
    fs::write(temp.path().join(".gitignore"), "ignored.rs\n").unwrap();
    fs::write(temp.path().join("ignored.rs"), "pub fn ignored() {}\n").unwrap();
    let first = index(&temp, &state);
    assert!(!first.files.iter().any(|file| file.path == "ignored.rs"));
    fs::write(
        temp.path().join("Cargo.toml"),
        "[package]\nname = \"fixture\"\nversion = \"0.2.0\"\nedition = \"2024\"\n[dependencies]\ndep = { path = \"dep\" }\n",
    )
    .unwrap();
    fs::write(
        temp.path().join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"dep\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"fixture\"\nversion = \"0.2.0\"\ndependencies = [\n \"dep\",\n]\n",
    )
    .unwrap();
    let changed = index(&temp, &state);
    assert!(
        changed
            .cargo
            .packages
            .iter()
            .any(|package| package.name == "fixture" && package.version == "0.2.0")
    );
}

